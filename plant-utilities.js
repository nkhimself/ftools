         const Q=q/3600,D=d/1000,g=9.80665,v=Q/(Math.PI*D*D/4),re=rho*v*D/(mu/1000),vel=v*v/(2*g);
         need(re<2300 || re>=4000,'عدد رینولدز در ناحیهٔ گذار است؛ ضریب اصطکاک قطعی نیست.');
